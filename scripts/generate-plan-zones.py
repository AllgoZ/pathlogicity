"""
Generates components/master-plan/officialZones.ts from the client's official master plan
(public/client/image-1731136566206.webp, 2774x1583).

Each zone is traced from the drawing's own colours (legend swatches + the unlabelled rail,
road and green fills), so highlights line up with the real drawing pixel-for-pixel.
The LEGEND -> ZONE mapping below is our reading of the drawing and MUST be confirmed by the
client; change ZONES and re-run if it differs:

    pip install numpy opencv-python-headless pillow
    python scripts/generate-plan-zones.py
"""
import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public/client/image-1731136566206.webp"
OUT = ROOT / "components/master-plan/officialZones.ts"

# drawing colours (sampled from the legend swatches / dominant fills)
COLOURS = {
    "warehouse": [(254, 226, 203)],
    "parking": [(246, 242, 173)],
    "commercial": [(216, 33, 38)],
    "open": [(193, 192, 179)],
    "cfs": [(198, 232, 246)],
    "transit": [(165, 70, 134)],
    "rail": [(248, 216, 128), (248, 216, 120)],
    "road_int": [(200, 200, 224), (200, 200, 232)],
    "green": [(8, 168, 88), (8, 168, 72)],
    "tree": [(88, 144, 64), (88, 152, 72), (88, 136, 56)],
}
TOL = {"commercial": 40, "cfs": 24, "green": 40, "tree": 44, "rail": 34, "road_int": 26}

# zone id (matches content/home.ts) -> drawing colours   (client to confirm)
ZONES = {
    "green": ["green", "tree"],
    "roads": ["road_dark", "road_int"],
    "yards": ["open", "parking"],
    "warehousing": ["warehouse", "transit"],
    "rail": ["rail"],
    "commercial": ["commercial"],
    "icd": ["cfs"],
}
CLOSE = {"warehouse": 9, "transit": 7, "parking": 7, "open": 7, "rail": 9, "commercial": 5, "cfs": 5, "green": 3, "tree": 3, "road_dark": 3, "road_int": 3}
ANCHORS = {"roads": (1146, 436)}  # the main entry roundabout reads better than the "deepest" point
GROW = {"icd": 10}  # tiny zones get a bigger hit area
MIN_AREA = {"icd": 120, "default": 700}
# the compass rose and legend (top-left) are black/colour ink that is not part of the site
IGNORE = (0, 0, 560, 760)

img = np.array(Image.open(SRC).convert("RGBA"))
H, W = img.shape[:2]
rgb = img[..., :3].astype(np.int32)
opaque = img[..., 3] > 200


def near(cs, tol):
    m = np.zeros((H, W), bool)
    for c in cs:
        m |= np.abs(rgb - np.array(c)).sum(axis=2) < tol
    return m & opaque


masks = {k: near(v, TOL.get(k, 18) * 1) for k, v in COLOURS.items()}
masks["road_dark"] = (rgb.max(axis=2) < 64) & opaque


def clean(m, k):
    m = m.astype(np.uint8)
    x0, y0, x1, y1 = IGNORE
    m[y0:y1, x0:x1] = 0
    s = CLOSE.get(k, 5)
    m = cv2.morphologyEx(m, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (s, s)))
    return m


def path_from(mask, min_area):
    cnts, hier = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
    parts = []
    for c, h in zip(cnts, hier[0]):
        a = cv2.contourArea(c)
        if a < (min_area if h[3] < 0 else min_area * 0.6):
            continue
        ap = cv2.approxPolyDP(c, 1.6, True).reshape(-1, 2)
        if len(ap) < 3:
            continue
        parts.append("M" + "L".join(f"{x} {y}" for x, y in ap) + "Z")
    return "".join(parts)


def anchor(mask):
    n, lab, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)
    if n < 2:
        return [W // 2, H // 2]
    best = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
    comp = (lab == best).astype(np.uint8)
    dist = cv2.distanceTransform(comp, cv2.DIST_L2, 5)
    y, x = np.unravel_index(np.argmax(dist), dist.shape)
    return [int(x), int(y)]


out = {}
for zid, cols in ZONES.items():
    m = np.zeros((H, W), np.uint8)
    for k in cols:
        m |= clean(masks[k], k)
    if zid in GROW:
        g = GROW[zid]
        m = cv2.dilate(m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (g, g)))
    d = path_from(m, MIN_AREA.get(zid, MIN_AREA["default"]))
    out[zid] = {"d": d, "anchor": list(ANCHORS[zid]) if zid in ANCHORS else anchor(m), "share": round(float(m.mean()) * 100, 2)}
    print(zid, "chars", len(d), "share%", out[zid]["share"], "anchor", out[zid]["anchor"])

ts = f"""/**
 * GENERATED by scripts/generate-plan-zones.py — do not edit by hand.
 * Zone regions traced from the client's official master plan
 * (public/client/image-1731136566206.webp, {W}x{H}). The legend -> zone mapping is our
 * reading of the drawing and is pending client confirmation (see the script header).
 */
export const OFFICIAL_PLAN = {{ width: {W}, height: {H}, src: "/client/image-1731136566206.webp" }} as const;

export const officialZones: Record<string, {{ d: string; anchor: [number, number] }}> = {json.dumps({k: {"d": v["d"], "anchor": v["anchor"]} for k, v in out.items()}, indent=2)};
"""
OUT.write_text(ts, encoding="utf-8")
print("wrote", OUT, OUT.stat().st_size // 1024, "KB")
